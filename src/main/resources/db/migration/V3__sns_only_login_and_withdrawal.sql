-- 로그인 수단을 SNS(카카오·Google·Apple)로만 한정하고, 회원 탈퇴에 필요한 구조를 추가한다.

-- 1. 이메일 로그인(LOCAL) 수단을 지운다.
delete from auth_credentials where provider = 'LOCAL';

-- 2. 로그인 수단이 하나도 남지 않은 회원(이메일로만 가입한 개발용 시험 계정)과 그 데이터를 지운다.
--    이 회원들은 더 이상 로그인할 수 없다. 데이터를 남기면 주인 없는 개인정보가 된다.
--    S3의 결과 파일과 Typecast의 내 목소리는 SQL로 지울 수 없다. 개발 데이터라서 남겨 둔다.
delete from memo_tags
where memo_id in (select id from memos where member_id not in (select member_id from auth_credentials));
delete from memos where member_id not in (select member_id from auth_credentials);
delete from dubbing_jobs where member_id not in (select member_id from auth_credentials);
delete from custom_voices where member_id not in (select member_id from auth_credentials);
delete from refresh_tokens where member_id not in (select member_id from auth_credentials);
delete from members where id not in (select member_id from auth_credentials);

-- 3. 비밀번호 컬럼을 지운다. 이제 모든 수단은 SNS 쪽 사용자 id를 가진다.
alter table auth_credentials drop column password;
alter table auth_credentials alter column provider_id set not null;

-- 4. 같은 이메일이라도 로그인 수단이 다르면 다른 계정이다 (PRD 9.17). 이메일 유니크 제약을 지운다.
alter table members drop constraint uk_members_email;

-- 5. 프로필 사진: SNS가 준 사진 주소. 동의하지 않았거나 Apple 로그인이면 없다.
alter table members add column profile_image_url varchar(500);

-- 6. 탈퇴할 때 SNS 연결을 철회하는 데 쓰는 토큰 (암호화한 값). 지금은 Apple만 저장한다.
alter table auth_credentials add column revoke_token varchar(1000);

-- 7. 탈퇴 후처리 작업. 카카오 연결 끊기, Apple 토큰 취소, 다른 도메인의 데이터 정리를 Worker가 재시도하며 처리한다.
--    처리가 끝난 행은 기록으로 남기고, 개인정보인 target은 지운다.
create table withdrawal_tasks (
    id              bigint generated by default as identity primary key,
    member_id       bigint        not null,  -- 탈퇴한 회원 id (회원 행은 이미 없다)
    type            varchar(30)   not null,  -- KAKAO_UNLINK / APPLE_REVOKE / DATA_CLEANUP
    target          varchar(1000),           -- 처리 대상 (카카오 회원번호, 암호화한 Apple 토큰, 정리할 도메인 이름)
    status          varchar(20)   not null,
    attempts        integer       not null,
    next_attempt_at timestamp(6)  not null,  -- 이 시각이 지나야 다시 시도한다 (재시도 간격)
    last_error      varchar(500),            -- 마지막 실패 사유 (운영 확인용)
    created_at      timestamp(6)  not null,
    started_at      timestamp(6),
    completed_at    timestamp(6)
);

-- Worker의 "다음 작업 꺼내기" 쿼리용
create index idx_withdrawal_tasks_status_next on withdrawal_tasks (status, next_attempt_at, id);
-- 탈퇴할 때 회원의 refresh 토큰을 지우는 쿼리용
create index idx_refresh_tokens_member_id on refresh_tokens (member_id);
