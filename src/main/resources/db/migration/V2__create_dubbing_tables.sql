-- 더빙 기능 (Typecast TTS).
-- 결과 오디오 파일은 S3에 두고, DB에는 작업 상태와 S3 객체 키만 둔다.
-- members로의 FK는 걸지 않는다 (도메인 경계 규칙: id 참조만 — memos와 같은 방식).

-- 내 목소리: 회원이 녹음으로 복제한 목소리. 회원당 1개.
-- 같은 회원이 동시에 두 번 등록을 요청해도 uk_custom_voices_member가 마지막 방어선이 된다.
create table custom_voices (
    id                bigint generated by default as identity primary key,
    member_id         bigint       not null,
    name              varchar(30)  not null,
    provider_voice_id varchar(100) not null,  -- TTS 업체가 발급한 목소리 id (앱에 노출 금지)
    consented_at      timestamp(6) not null,  -- 복제 동의 시각
    created_at        timestamp(6) not null,
    constraint uk_custom_voices_member unique (member_id)
);

-- 더빙 작업. Worker가 PENDING 작업을 하나씩 꺼내 처리한다 (DB를 큐로 사용).
-- preset_voice와 custom_voice_id 중 하나에만 값이 있다.
-- 목소리가 삭제되면 custom_voice_id가 null이 되므로, "둘 중 하나는 필수" CHECK 제약은 두지 않는다.
create table dubbing_jobs (
    id              bigint generated by default as identity primary key,
    member_id       bigint        not null,
    text            varchar(2000) not null,
    preset_voice    varchar(30),
    custom_voice_id bigint,
    status          varchar(20)   not null,
    attempts        integer       not null,
    audio_key       varchar(200),             -- 결과 mp3의 S3 객체 키 (COMPLETED일 때만)
    failure_reason  varchar(500),             -- 마지막 실패 사유 (운영 확인용)
    created_at      timestamp(6)  not null,
    started_at      timestamp(6),
    completed_at    timestamp(6),
    constraint fk_dubbing_jobs_custom_voice foreign key (custom_voice_id)
        references custom_voices (id) on delete set null
);

-- Worker의 "다음 작업 꺼내기" 쿼리용 (status 조건 + id 순서)
create index idx_dubbing_jobs_status_id on dubbing_jobs (status, id);
-- 내 더빙 목록 조회용
create index idx_dubbing_jobs_member_id on dubbing_jobs (member_id, id);
